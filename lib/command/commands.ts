import type { CommandItem } from "@/lib/command/types";

function nav(
  partial: Omit<CommandItem, "section" | "keywords"> & {
    keywords?: string[];
  }
): CommandItem {
  return {
    section: "navigate",
    category: "Navigation",
    keywords: partial.keywords || [partial.title],
    ...partial,
  };
}

function act(
  partial: Omit<CommandItem, "section" | "keywords"> & {
    keywords?: string[];
    category?: CommandItem["category"];
  }
): CommandItem {
  return {
    section: "action",
    category: partial.category || "Creation",
    keywords: partial.keywords || [partial.title],
    ...partial,
  };
}

