export const ALL_STATIC_COMMANDS: CommandItem[] = [
  ...COMMAND_ACTIONS,
  ...COMMAND_NAVIGATE,
];

export function commandsForPath(pathname: string): CommandItem[] {
  return ALL_STATIC_COMMANDS.filter(
    (c) =>
      c.contexts?.some(
        (ctx) => pathname === ctx || pathname.startsWith(`${ctx}/`)
      )
  );
}

export function enrichCommandShortcuts(
  items: CommandItem[],
  labelFor: (shortcutId: string) => string | undefined
): CommandItem[] {
  return items.map((c) => ({
    ...c,
    shortcut: c.shortcutId ? labelFor(c.shortcutId) || c.shortcut : c.shortcut,
  }));
}
